import test from "node:test";
import assert from "node:assert/strict";
import {
  readMaterial,
  sha256,
  modelBatches,
  modelMaterial,
} from "./material.mjs";
import { xlsxBytes, inline, SHEET_NS } from "./xlsx-fixtures.mjs";
import { utils, write } from "xlsx/xlsx.mjs";
const read = (body, options) =>
  readMaterial(
    {
      id: "xlsx",
      name: "合成.xlsx",
      body,
      size: body.length,
      hash: sha256(body),
    },
    options,
  );
test("XLSX generated by the existing SheetJS writer reads real package relationships and unambiguous built-in date years", () => {
  const book = utils.book_new(),
    sheet = utils.aoa_to_sheet([
      ["真实生成😀", new Date(Date.UTC(2026, 9, 28, 12)), 0.125],
      ["尾标", 7, true],
    ]);
  sheet.C1.z = "0.00%";
  utils.book_append_sheet(book, sheet, "真实表");
  const value = read(write(book, { type: "buffer", bookType: "xlsx" }));
  assert.equal(value.state, "read");
  assert.match(value.segments.map((s) => s.text).join(""), /日期 2026-10-28/);
  assert.match(value.segments[0].text, /C1\t12.50%/);
  assert.equal(value.covered.at(-1).row, 2);
});
test("XLSX infers omitted row/cell coordinates and distinguishes absent formula caches from empty cached strings", () => {
  const value = read(
    xlsxBytes([
      {
        name: "隐式坐标",
        xml: `<row><c t="inlineStr"><is><t>首格</t></is></c><c><f>1+1</f><v/></c><c t="str"><f>\"\"</f><v/></c></row><row>${inline("B2", "第二行")}</row>`,
      },
    ]),
  );
  assert.equal(value.state, "partial");
  assert.match(value.segments[0].text, /A1\t首格/);
  assert.match(value.segments[0].text, /B1\t \[公式无缓存，未计算/);
  assert.ok(
    value.uncovered.some(
      (r) => r.code === "XLSX_FORMULA_NO_CACHE" && r.cell === "B1",
    ),
  );
  assert.ok(
    !value.uncovered.some(
      (r) => r.code === "XLSX_FORMULA_NO_CACHE" && r.cell === "C1",
    ),
  );
  assert.equal(value.covered.at(-1).row, 2);
});
test("XLSX safety resource failures are failed, while uncertain inherited number formatting preserves raw values as partial", () => {
  const bomb = read(
    xlsxBytes(undefined, { "padding.xml": "A".repeat(1000000) }, { level: 6 }),
  );
  assert.equal(bomb.state, "failed");
  assert.ok(bomb.reasons.includes("PACKAGE_LIMIT"));
  const inherited = read(
    xlsxBytes(
      [
        {
          name: "继承格式",
          xml: '<row r="1"><c r="A1"><v>45000</v></c></row>',
        },
      ],
      {
        "xl/styles.xml": `<styleSheet xmlns="${SHEET_NS}"><cellXfs><xf numFmtId="0" xfId="1" applyNumberFormat="0"/></cellXfs></styleSheet>`,
      },
    ),
  );
  assert.equal(inherited.state, "partial");
  assert.equal(inherited.segments[0].text, "A1\t45000\n");
  assert.ok(inherited.reasons.includes("XLSX_FORMAT_UNREAD"));
});
test("XLSX preserves workbook order, rich shared/inline strings, sparse coordinates, date/percent display and merge/hidden metadata without a giant dimension grid", () => {
  const bytes = xlsxBytes([
    {
      name: "先读",
      visibility: "hidden",
      xml: '<row r="2" hidden="1"><c r="B2" t="s"><v>0</v></c><c r="D2" s="1"><v>1.5</v></c><c r="G2" s="2"><v>0.125</v></c></row>',
      after: '<mergeCells><mergeCell ref="B2:C3"/></mergeCells>',
    },
    {
      name: "后读",
      xml: `<row r="9">${inline("C9", " 第二表\n😀 尾部 ")}<c r="Z9" t="b"><v>1</v></c></row>`,
    },
  ]);
  const value = read(bytes);
  assert.equal(value.state, "read");
  assert.deepEqual(
    value.segments.map((s) => s.range.sheet),
    ["先读", "后读"],
  );
  assert.equal(
    value.segments[0].text,
    "B2\t 共享 😀 & 单元格\nD2\t1900-01-01 12:00 [日期 1900-01-01]\nG2\t12.50%\n",
  );
  assert.equal(value.segments[1].text, "C9\t 第二表\n😀 尾部 \nZ9\tTRUE\n");
  assert.deepEqual(
    value.segments[0].structure.columns.map((c) => c.column),
    [2, 4, 7],
  );
  assert.equal(value.segments[0].structure.hidden, true);
  assert.equal(value.segments[0].structure.sheetVisibility, "hidden");
  assert.deepEqual(value.segments[0].structure.merges, [
    { start: { row: 2, column: 2 }, end: { row: 3, column: 3 }, ref: "B2:C3" },
  ]);
  const alternate = read(
    xlsxBytes(
      [
        {
          name: "1904",
          xml: '<row r="1"><c r="A1" s="1"><v>0.5</v></c></row>',
        },
      ],
      {},
      { date1904: true },
    ),
  );
  assert.equal(
    alternate.segments[0].text,
    "A1\t1904-01-01 12:00 [日期 1904-01-01]\n",
  );
});
test("XLSX formula cached values, missing cache, errors, external links and objects remain explicit partial with no evaluation/fetch", () => {
  const bytes = xlsxBytes(
    [
      {
        name: "缓存",
        xml: '<row r="1"><c r="A1"><f>1+1</f><v>999</v></c><c r="B1"><f>WEBSERVICE("http://invalid.test")</f></c><c r="C1" t="e"><v>#DIV/0!</v></c></row>',
        after: "<drawing/>",
      },
    ],
    {
      "xl/worksheets/_rels/sheet1.xml.rels":
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="outside" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/hyperlink" Target="https://invalid.test/secret" TargetMode="External"/></Relationships>',
    },
  );
  const value = read(bytes);
  assert.equal(value.state, "partial");
  assert.match(value.segments[0].text, /999 \[公式缓存，未重算；1\+1\]/);
  assert.ok(value.reasons.includes("XLSX_FORMULA_NO_CACHE"));
  assert.ok(value.reasons.includes("XLSX_EXTERNAL_LINK"));
  assert.ok(value.reasons.includes("XLSX_CELL_ERROR"));
  assert.ok(value.reasons.includes("XLSX_OBJECT_UNREAD"));
  assert.equal(
    value.uncovered.find((r) => r.code === "XLSX_FORMULA_NO_CACHE").cell,
    "B1",
  );
});
test("XLSX escaped control/literal sequences retain Unicode and an all-empty workbook has no fabricated readable material", () => {
  const value = read(
    xlsxBytes([
      {
        name: "转义",
        xml: `<row r="1">${inline("A1", "a_x000D_b_x005F_x0041__xD83D__xDE00_")}</row>`,
      },
    ]),
  );
  assert.equal(value.segments[0].text, "A1\ta\nb_x0041_😀\n");
  const empty = read(
    xlsxBytes([
      { name: "空", xml: `<row r="1">${inline("A1", "   ")}<c r="B1"/></row>` },
    ]),
  );
  assert.equal(empty.segments.length, 0);
  assert.ok(empty.reasons.includes("EMPTY_TEXT"));
});
test("XLSX damaged sheet tail retains only complete rows, continues later sheets and identifies invalid shared-string/coordinate ranges", () => {
  const value = read(
    xlsxBytes([
      {
        name: "损坏",
        fullXml: `<worksheet xmlns="${SHEET_NS}"><sheetData><row r="1">${inline("A1", "完整行")}</row><row r="2">${inline("A2", "不完整行")}<c r="B2">`,
      },
      { name: "后表", xml: `<row r="4">${inline("D4", "后表依旧完整")}</row>` },
    ]),
  );
  assert.equal(value.state, "partial");
  assert.equal(value.segments.length, 2);
  assert.ok(!value.segments.some((s) => s.text.includes("不完整行")));
  assert.equal(
    value.uncovered.find((r) => r.code === "XLSX_XML_MALFORMED").row,
    2,
  );
  for (const cell of [
    '<c r="XFE1"><v>2</v></c>',
    '<c r="A1" t="s"><v>99</v></c>',
  ]) {
    const invalid = read(
      xlsxBytes([{ name: "无效", xml: `<row r="1">${cell}</row>` }]),
    );
    assert.equal(invalid.state, "failed");
    assert.equal(invalid.segments.length, 0);
  }
});
test("XLSX long cells cross every window losslessly with stable worksheet/cell metadata", () => {
  const text = "长单元格😀\n".repeat(30000) + "唯一尾标";
  const value = read(
    xlsxBytes([
      { name: "长表", xml: `<row r="100">${inline("D100", text)}</row>` },
    ]),
  );
  assert.equal(value.state, "read");
  assert.equal(
    value.segments.map((s) => s.text).join(""),
    "D100\t" + text + "\n",
  );
  assert.ok(value.segments.length > 1);
  assert.equal(value.segments.at(-1).range.row, 100);
  const batches = [...modelBatches([modelMaterial(value)])];
  assert.equal(
    batches
      .flat()
      .map((s) => s.text)
      .join(""),
    "D100\t" + text + "\n",
  );
});
test("XLSX rejects unsafe package paths, macros, encrypted Office, DTD and invalid workbook roots before returning source text", () => {
  const samples = [
    xlsxBytes(undefined, { "../escape": "bad" }),
    xlsxBytes(undefined, { "xl/vbaProject.bin": "bad" }),
    xlsxBytes(undefined, {
      "xl/workbook.xml": `<!DOCTYPE workbook [<!ENTITY x SYSTEM "file:///etc/passwd">]><workbook xmlns="${SHEET_NS}"/>`,
    }),
    xlsxBytes(undefined, {
      "xl/workbook.xml": '<workbook xmlns="http://invalid.test"/>',
    }),
    Buffer.from([0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1, 0]),
  ];
  for (const bytes of samples) {
    const value = read(bytes);
    assert.ok(["failed", "unsupported"].includes(value.state));
    assert.equal(value.segments.length, 0);
    assert.ok(value.uncovered.length);
  }
});
