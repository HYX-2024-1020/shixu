test("literal member selection preserves directories, emoji, wildcard and @ names; duplicates/count fail closed", async () => {
  const m = await read(
    rarBytes({
      "目录/😀.txt": "one",
      "@file.txt": "two",
      "a?.txt": "three",
      "a*.txt": "four",
      "-switch.txt": "tail",
    }),
  );
  assert.equal(m.segments.map((s) => s.text).join(""), "onetwothreefourtail");
  assert.deepEqual(
    m.covered.map((r) => r.archivePath),
    ["目录/😀.txt", "@file.txt", "a?.txt", "a*.txt", "-switch.txt"],
  );
  const duplicate = await read(
    rarBytes([
      ["a.txt", "never"],
      ["a.txt", "also never"],
    ]),
  );
  assert.deepEqual(duplicate.segments, []);
  assert.equal(duplicate.reasons[0], "PACKAGE_PATH");
  const many = await read(
    rarBytes(
      Object.fromEntries(
        Array.from({ length: 1001 }, (_, i) => [i + ".txt", "x"]),
      ),
    ),
  );
  assert.deepEqual(many.segments, []);
  assert.equal(many.reasons[0], "PACKAGE_LIMIT");
});
test("encrypted and expansion-ratio 7z are rejected; bounded solid members are read", async () => {
  const encrypted = await sevenZipBytes({ "a.txt": Buffer.from("never") }, [
    "-pSyntheticOnly",
    "-mhe=on",
  ]);
  assert.deepEqual((await read(encrypted, "a.7z")).segments, []);
  const solid = await sevenZipBytes(
    { "a.txt": Buffer.from("never"), "b.txt": Buffer.from("never") },
    ["-ms=on", "-mx=1"],
  );
  const shared=await read(solid, "a.7z");assert.equal(shared.state,"read");assert.equal(shared.segments.map(s=>s.text).join(""),"nevernever");assert.equal(shared.archiveCompression.blocks.length,1);
  const bomb = await sevenZipBytes(
    { "a.txt": Buffer.from("x".repeat(200000)) },
    ["-mx=9"],
  );
  assert.equal((await read(bomb, "a.7z")).reasons[0], "PACKAGE_LIMIT");
});
