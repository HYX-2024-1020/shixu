import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { createRequire } from "node:module";
import { Resvg } from "@resvg/resvg-js";

const root = fileURLToPath(new URL("../", import.meta.url));
const check = process.argv.includes("--check");
const outputs = new Map();
const bundled = await build({
  stdin: {
    contents: `export { BUILTIN_SKINS, SKIN_MOTIONS, MAX_CUSTOM_SKINS, parseSkinCollection, isSkinImage } from './src/bucket/skins';
    export { absoluteItem, absoluteText, setDeadline, parseDeadline, deadlineSections } from './shared/deadlines.mjs';
    export { compareItems } from './src/bucket/management';
    export { cardCopy } from './src/bucket/card-copy';
    export { mergeCardOrder } from './src/bucket/card-order';
    export { buildGroups, itemRef } from './shared/relations.mjs';`,
    resolveDir: root,
  },
  bundle: true,
  write: false,
  format: "cjs",
  platform: "neutral",
  target: "es2018",
  define: { "Object.hasOwn": "Object.prototype.hasOwnProperty.call" },
  legalComments: "none",
  charset: "utf8",
});
outputs.set(
  "miniprogram/lib/generated/desktop.js",
  Buffer.from(
    "// Generated by npm run mini:build. Edit the desktop/shared source instead.\n" +
      bundled.outputFiles[0].text,
  ),
);
const ai = await build({
  stdin: {
    contents: `export { organizePacket, DEFAULT_MODEL } from './shared/bucket-engine.mjs'; export { chatWithItem } from './src/bucket/item-chat';`,
    resolveDir: root,
  },
  bundle: true,
  write: false,
  format: "esm",
  platform: "node",
  target: "node24",
  charset: "utf8",
  legalComments: "none",
});
outputs.set(
  "server/generated/ai-core.mjs",
  Buffer.from(
    "// Generated from the same desktop organizer/chat code.\n" +
      ai.outputFiles[0].text,
  ),
);
outputs.set(
  "desktop/generated/sync-client.cjs",
  await readFile(path.join(root, "miniprogram/lib/sync-client.js")),
);
const renderer = await build({
  stdin: {
    contents: `import React from 'react'; import { renderToStaticMarkup } from 'react-dom/server';
    import SkinArt from './src/bucket/SkinArt'; import { BUILTIN_SKINS } from './src/bucket/skins';
    module.exports = BUILTIN_SKINS.filter(s => s.art !== 'whale').map(s => [s.id, renderToStaticMarkup(React.createElement(SkinArt, {skin:s}))]);`,
    resolveDir: root,
  },
  bundle: true,
  write: false,
  format: "cjs",
  platform: "node",
  jsx: "automatic",
  external: ["react", "react-dom/server"],
  define: { "import.meta.env.BASE_URL": '"/"' },
});
const module = { exports: {} };
new Function("module", "exports", "require", renderer.outputFiles[0].text)(
  module,
  module.exports,
  createRequire(import.meta.url),
);
for (const [id, svg] of module.exports)
  outputs.set(
    `miniprogram/assets/skins/${id}.png`,
    new Resvg(svg).render().asPng(),
  );
outputs.set(
  "miniprogram/assets/mascot.png",
  await readFile(path.join(root, "public/mascot.png")),
);
outputs.set(
  "miniprogram/assets/laugh.mp3",
  await readFile(path.join(root, "public/laugh.mp3")),
);
const hashes = Object.fromEntries(
  [...outputs].map(([name, bytes]) => [
    name,
    createHash("sha256").update(bytes).digest("hex"),
  ]),
);
outputs.set(
  "miniprogram/lib/generated/manifest.json",
  Buffer.from(
    JSON.stringify({ source: "desktop/shared", files: hashes }, null, 2) + "\n",
  ),
);
let stale = false;
for (const [name, bytes] of outputs) {
  const target = path.join(root, name);
  if (check) {
    const current = await readFile(target).catch(() => null);
    if (!current?.equals(bytes)) {
      console.error(`Outdated: ${name}; run npm run mini:build`);
      stale = true;
    }
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, bytes);
  }
}
if (stale) process.exitCode = 1;
else
  console.log(
    `Mini shared code and desktop artwork ${check ? "verified" : "generated"} (${outputs.size} files).`,
  );
