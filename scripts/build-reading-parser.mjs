import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import "./build-reading-pdf.mjs";
// The sandbox mounts only /reader and its fixed runtime, never node_modules.
// The fixture encoder is excluded from the production release allowlist.
for (const codec of ["decoder", "encoder"]) {
  const entry = new URL(
    "../node_modules/jpeg-js/lib/" + codec + ".js",
    import.meta.url,
  );
  const source = await readFile(entry, "utf8");
  let strictSource = source;
  if (codec === "decoder") {
    const suffixStart = source.indexOf(
      "      if (mcu === mcuExpected) {\n        // Skip trailing bytes",
    );
    const suffixEnd = source.indexOf("      // find marker", suffixStart);
    if (suffixStart < 0 || suffixEnd < 0)
      throw Error("JPEG_PATCH_ANCHOR_MISMATCH");
    strictSource =
      source.slice(0, suffixStart) +
      '      if (bitsCount && (bitsData & ((1 << bitsCount)-1)) !== ((1 << bitsCount)-1)) throw new Error("strict JPEG padding");\n' +
      '      if (eobrun !== 0) throw new Error("strict JPEG EOB run");\n' +
      "      while (data[offset] === 255 && data[offset+1] === 255) offset++;\n" +
      '      if (data[offset] !== 255 || data[offset+1] === 0) throw new Error("strict JPEG scan suffix");\n\n' +
      source.slice(suffixEnd);
    const loop = "for (n = 0; n < resetInterval; n++)";
    if (strictSource.split(loop).length !== 3)
      throw Error("JPEG_PATCH_LOOP_MISMATCH");
    strictSource = strictSource.replaceAll(
      loop,
      "for (n = 0; n < resetInterval && mcu < mcuExpected; n++)",
    );
  }
  const result = await build({
    stdin: { contents: strictSource, sourcefile: codec + ".js", loader: "js" },
    bundle: true,
    platform: "node",
    format: "cjs",
    write: false,
    legalComments: "inline",
    minify: true,
  });
  const stem = codec === "decoder" ? "jpeg-reader" : "fixtures/jpeg-encoder";
  const license =
    (await readFile(
      new URL("../node_modules/jpeg-js/LICENSE", import.meta.url),
      "utf8",
    )) +
    "\n\njpeg-js 0.4.4 " +
    codec +
    " upstream notice:\n" +
    source.slice(
      0,
      source.indexOf(codec === "decoder" ? "var JpegImage" : "var btoa"),
    ) +
    (codec === "decoder"
      ? "\n" +
        (await readFile(
          new URL("../node_modules/pdfjs-dist/LICENSE", import.meta.url),
          "utf8",
        ))
      : "");
  const generated =
    (codec === "decoder"
      ? "// Shixu modification: strict scan padding/EOB/suffix and bounded final restart interval.\n"
      : "") +
    "// Generated pinned jpeg-js 0.4.4 " +
    codec +
    "; see " +
    stem.split("/").at(-1) +
    ".LICENSE.\n" +
    result.outputFiles[0].text;
  // Preserve every notice/condition while keeping generated text compatible
  // with the repository's whitespace gate on both platforms.
  const normalizedLicense=license.replaceAll('\r\n','\n').replace(/[ \t]+$/gm,'').trimEnd()+'\n';
  for (const [name, body] of [
    [stem + ".cjs", generated],
    [stem + ".LICENSE", normalizedLicense],
  ]) {
    const path = new URL("../server/reading/" + name, import.meta.url);
    if (process.argv.includes("--check")) {
      if ((await readFile(path, "utf8")) !== body)
        throw Error("STALE_JPEG_READER");
    } else await writeFile(path, body);
  }
}
for (const format of ["docx", "xlsx"]) {
  const result = await build({
    entryPoints: [
      fileURLToPath(
        new URL(`../server/reading/${format}.mjs`, import.meta.url),
      ),
    ],
    bundle: true,
    platform: "node",
    format: "cjs",
    write: false,
    legalComments: "inline",
    minify: true,
  });
  const output = new URL(
    `../server/reading/${format}-reader.cjs`,
    import.meta.url,
  );
  const generated =
    `// Generated by scripts/build-reading-parser.mjs; see ${format}-reader.LICENSE.\n` +
    result.outputFiles[0].text;
  const license =
    (await readFile(
      new URL("../node_modules/sax/LICENSE.md", import.meta.url),
      "utf8",
    )) +
    (format === "xlsx"
      ? "\n\nSheetJS 0.20.3 (SSF number formatting):\n" +
        (await readFile(
          new URL("../node_modules/xlsx/LICENSE", import.meta.url),
          "utf8",
        ))
      : "");
  if (process.argv.includes("--check")) {
    if ((await readFile(output, "utf8")) !== generated)
      throw Error("STALE_READING_PARSER");
    if (
      (await readFile(
        new URL(`../server/reading/${format}-reader.LICENSE`, import.meta.url),
        "utf8",
      )) !== license
    )
      throw Error("STALE_READING_LICENSE");
  } else {
    await writeFile(output, generated);
    await writeFile(
      new URL(`../server/reading/${format}-reader.LICENSE`, import.meta.url),
      license,
    );
  }
}
console.log("Reading XML parser bundle verified/generated");
