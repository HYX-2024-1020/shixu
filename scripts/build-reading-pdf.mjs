import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const pkg = JSON.parse(
  await readFile(new URL("node_modules/pdfjs-dist/package.json", root)),
);
if (pkg.version !== "6.2.108") throw Error("REVIEW_PDFJS_UPGRADE_REQUIRED");
for (const [name, input] of [
  ["api", "pdf"],
  ["core", "pdf.worker"],
]) {
  let source = await readFile(
    new URL(`node_modules/pdfjs-dist/build/${input}.mjs`, root),
    "utf8",
  );
  // Node24 on the deployed runtime lacks the new Uint8Array hex helpers. Use
  // a local pure function, not global prototype patches or legacy canvas code.
  source = source.replace(
    /([\w.]+)\.toHex\(\)/g,
    "Array.from($1, b => b.toString(16).padStart(2, '0')).join('')",
  );
  if (name === "api") {
    // Upstream eagerly creates a rendering-only matrix at module load. Text
    // extraction never uses it. Fail closed if rendering is accidentally used;
    // do not ship a fake DOM/canvas implementation or native canvas binary.
    const eager = "const SCALE_MATRIX = new DOMMatrix();";
    if (source.split(eager).length !== 2)
      throw Error("REVIEW_PDF_RENDER_ADAPTATION");
    source = source.replace(eager, "const SCALE_MATRIX = null;");
    const warning =
      'warn("Please use the `legacy` build in Node.js environments.");';
    if (source.split(warning).length !== 2)
      throw Error("REVIEW_PDF_NODE_WARNING");
    source = source.replace(warning, "");
  }
  const result = await build({
    stdin: {
      contents: source,
      sourcefile: `${input}.mjs`,
      resolveDir: fileURLToPath(root),
    },
    bundle: true,
    platform: "node",
    format: "esm",
    write: false,
    minify: true,
    legalComments: "inline",
  });
  const target = new URL(`server/reading/pdf-${name}.mjs`, root);
  const content =
    "// Generated by scripts/build-reading-pdf.mjs; see pdf-reader.LICENSE.\n" +
    result.outputFiles[0].text;
  if (process.argv.includes("--check")) {
    if ((await readFile(target, "utf8")) !== content)
      throw Error("STALE_PDF_BUNDLE");
  } else await writeFile(target, content);
}
const license = await readFile(
  new URL("node_modules/pdfjs-dist/LICENSE", root),
);
const target = new URL("server/reading/pdf-reader.LICENSE", root);
if (process.argv.includes("--check")) {
  if (!(await readFile(target)).equals(license))
    throw Error("STALE_PDF_LICENSE");
} else await writeFile(target, license);
console.log("PDF text-only API/core bundles verified/generated");
